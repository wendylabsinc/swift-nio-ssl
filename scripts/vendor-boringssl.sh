# This script creates a vendored copy of BoringSSL that is
# suitable for building with the Swift Package Manager.
#
# Usage:
#   1. Run this script in the package root, passing the BoringSSL revision to
#      vendor:
#          scripts/vendor-boringssl.sh <boringssl-revision>
#      It will place a local copy of the BoringSSL sources in
#      Sources/CNIOBoringSSL. Any prior contents of Sources/CNIOBoringSSL will
#      be deleted.
#
# Symbol prefixing:
#   Modern BoringSSL ships the symbol-prefixing headers itself
#   (include/openssl/prefix_symbols.h and friends, generated by
#   `go ./util/pregenerate`). When BORINGSSL_PREFIX is defined, base.h pulls
#   them in; they rename every exported symbol to CNIOBoringSSL_*. This replaces
#   the old machinery (util/read_symbols.go + util/make_prefix_headers.go, run
#   across macOS/iOS/Linux builds) that this script used to carry, and no longer
#   needs a macOS/Docker/Go toolchain to run.
#
#   prefix_symbols.h renames symbols one of two ways: `#pragma redefine_extname`
#   (the default on clang/gcc), which renames only the *linked* symbol and
#   leaves the source identifier unprefixed, or - in its #else branch - plain
#   `#define X CNIOBoringSSL_X` token substitution, which also renames the
#   identifier the Swift ClangImporter sees. NIOSSL is written against the
#   CNIOBoringSSL_-prefixed identifiers, so we force the token-substitution
#   branch by undefining __PRAGMA_REDEFINE_EXTNAME (see enable_prefixing).
set -eou pipefail

HERE=$(pwd)
DSTROOT=Sources/CNIOBoringSSL
TMPDIR=$(mktemp -d /tmp/.workingXXXXXX)
SRCROOT="${TMPDIR}/src/boringssl.googlesource.com/boringssl"
BORINGSSL_TARGET_REVISION="${1:?Usage: $0 <boringssl-revision>}"

case "$(uname -s)" in
    Darwin)
        sed=gsed
        ;;
    *)
	# shellcheck disable=SC2209
        sed=sed
        ;;
esac

if ! hash ${sed} 2>/dev/null; then
    echo "You need sed \"${sed}\" to run this script ..."
    echo
    echo "On macOS: brew install gnu-sed"
    exit 43
fi

# Enables BoringSSL's shipped symbol prefixing. See the header comment.
function enable_prefixing {
    echo "ENABLING symbol prefixing"
    # C/C++: define BORINGSSL_PREFIX so base.h includes prefix_symbols.h, and
    # #undef __PRAGMA_REDEFINE_EXTNAME so the header takes its token-substitution
    # branch (which renames the identifiers the Swift importer sees, not just the
    # linked symbols). Both are injected right after base.h's header guard so
    # they are in scope before base.h includes prefix_symbols.h.
    perl -pi -e '$_ .= qq(\n#define BORINGSSL_PREFIX CNIOBoringSSL\n#undef __PRAGMA_REDEFINE_EXTNAME\n) if /#define OPENSSL_HEADER_BASE_H/' "$DSTROOT/include/openssl/base.h"
    # Assembly: prefix_symbols.h guards its pragma branch on !__ASSEMBLER__, so
    # each .S file only needs BORINGSSL_PREFIX defined before it includes
    # asm_base.h.
    while IFS= read -r -d '' assembly_file
    do
        $sed -i '1 i #define BORINGSSL_PREFIX CNIOBoringSSL' "$assembly_file"
    done <   <(find "$DSTROOT" -name "*.S" -print0)
}

echo "REMOVING any previously-vendored BoringSSL code"
rm -rf $DSTROOT/include
rm -rf $DSTROOT/ssl
rm -rf $DSTROOT/crypto
rm -rf $DSTROOT/third_party
rm -rf $DSTROOT/gen

echo "CLONING boringssl"
mkdir -p "$SRCROOT"
# BSSL_MIRROR may point at a local clone (file:///path) to vendor offline.
git clone "${BSSL_MIRROR:-https://boringssl.googlesource.com/boringssl}" "$SRCROOT"
cd "$SRCROOT"
git checkout "$BORINGSSL_TARGET_REVISION"
BORINGSSL_REVISION=$(git rev-parse HEAD)
cd "$HERE"
echo "CLONED boringssl@${BORINGSSL_REVISION}"

echo "OBTAINING submodules"
(
    cd "$SRCROOT"
    git submodule update --init || true
)

# NOTE: scripts/build-asm.py is no longer run. Modern BoringSSL ships its
# pre-generated assembly under gen/, which is what the copy patterns below pick
# up; build-asm.py emitted perlasm into <os>-<arch>/ directories that the copy
# patterns never referenced.

PATTERNS=(
'include/openssl/*.h'
'include/openssl/*/*.h'
'ssl/*.h'
'ssl/*.cc'
'crypto/*.h'
'crypto/*.cc'
'crypto/*/*.h'
'crypto/*/*.cc'
'crypto/*/*.S'
'crypto/*/*/*.h'
'crypto/*/*/*.cc.inc'
'crypto/*/*/*.inc'
'crypto/*/*/*.S'
'crypto/*/*/*/*.cc.inc'
'gen/crypto/*.cc'
'gen/crypto/*.S'
'gen/bcm/*.S'
'third_party/fiat/*.h'
'third_party/fiat/*.c.inc'
'third_party/fiat/asm/*.S'
)

EXCLUDES=(
'*_test.*'
'test_*.*'
'test'
'example_*.cc'
)

echo "COPYING boringssl"
for pattern in "${PATTERNS[@]}"
do
  for i in $SRCROOT/$pattern; do
    path=${i#"$SRCROOT"}
    dest="$DSTROOT$path"
    dest_dir=$(dirname "$dest")
    mkdir -p "$dest_dir"
    cp "$SRCROOT/$path" "$dest"
  done
done

for exclude in "${EXCLUDES[@]}"
do
  echo "EXCLUDING $exclude"
  find $DSTROOT -d -name "$exclude" -exec rm -rf {} \;
done

enable_prefixing

echo "RENAMING header files"
(
    # nullglob so an empty **/*.h (no nested headers remain after pki removal)
    # is skipped rather than passed literally to mv. Deliberately NOT globstar:
    # the loop below relies on ** collapsing to a single directory level, as the
    # original script did.
    shopt -s nullglob
    cd "$DSTROOT"

    # We need to rearrange a couple of things here, the end state will be:
    # - Headers from 'include/openssl/' will be moved up a level to 'include/'
    # - Their names will be prefixed with 'CNIOBoringSSL_'
    # - Any include of another header in the 'include/' directory will use
    #   quotation marks instead of angle brackets

    mv include/openssl/* include/
    rmdir "include/openssl"

    # Now let's remove the pki subdirectory, as we don't need it.
    rm -rf include/pki

    # Change the imports from "<openssl/X>" to "<CNIOBoringSSL_X>". Match *.inc
    # as well (covers *.cc.inc, *.c.inc and bare *.inc): modern BoringSSL splits
    # sources into fragments that also carry <openssl/...> includes.
    # shellcheck disable=SC2038
    find . -name "*.[ch]" -or -name "*.cc" -or -name "*.S" -or -name "*.inc" | xargs $sed -i -r -e 's#include <openssl/(([^/>]+/)*)(.+.h)>#include <\1CNIOBoringSSL_\3>#' -e 's#include "openssl/(([^/>]+/)*)(.+.h)"#include "\1CNIOBoringSSL_\3"#'

    # Okay now we need to rename the headers adding the prefix "CNIOBoringSSL_".
    pushd include
    for x in *.h; do mv -- "$x" "CNIOBoringSSL_${x}"; done
    for x in **/*.h; do mv -- "$x" "${x%/*}/CNIOBoringSSL_${x##*/}"; done

    # Finally, make sure we refer to them by their prefixed names, and change any
    # includes from angle brackets to quotation marks.
    # shellcheck disable=SC2038
    find . -name "*.h" | xargs $sed -i -r -e 's#include "(([^/"]+/)*)(.+.h)"#include "\1CNIOBoringSSL_\3"#' -e 's/include <CNIOBoringSSL_(.*)>/include "CNIOBoringSSL_\1"/'
    popd
)

echo "PATCHING BoringSSL"
git apply "${HERE}/scripts/patch-1-inttypes.patch" || echo "WARN: patch-1 did not apply (headers already include <inttypes.h> at this revision)"
git apply "${HERE}/scripts/patch-2-inttypes.patch" || echo "WARN: patch-2 did not apply (headers already include <inttypes.h> at this revision)"
git apply "${HERE}/scripts/patch-3-more-inttypes.patch" || echo "WARN: patch-3 did not apply (headers already include <inttypes.h> at this revision)"

# We need to avoid having the stack be executable. BoringSSL does this in its build system, but we can't.
echo "PROTECTING against executable stacks"
(
    cd "$DSTROOT"
    # shellcheck disable=SC2038
    find . -name "*.S" | xargs $sed -i '$ a #if defined(__linux__) && defined(__ELF__)\n.section .note.GNU-stack,"",%progbits\n#endif\n'
)

# We need BoringSSL to be modularised
echo "MODULARISING BoringSSL"
# Generate the umbrella from the set of shipped public headers rather than a
# hand-maintained list: the modern BoringSSL header layout no longer pulls (for
# example) obj.h / asn1.h / crypto.h / pem.h / mem.h in transitively, so a
# curated subset would leave symbols the NIOSSL shim uses unreachable to the
# Clang importer. Excluded: the umbrella itself and the prefix-symbol machinery
# headers (base.h / asm_base.h include those at the right time already).
(
    cd "$DSTROOT/include"
    {
        cat <<'HEADER'
//===----------------------------------------------------------------------===//
//
// This source file is part of the SwiftNIO open source project
//
// Copyright (c) 2019 Apple Inc. and the SwiftNIO project authors
// Licensed under Apache License v2.0
//
// See LICENSE.txt for license information
// See CONTRIBUTORS.txt for the list of SwiftNIO project authors
//
// SPDX-License-Identifier: Apache-2.0
//
//===----------------------------------------------------------------------===//
#ifndef C_NIO_BORINGSSL_H
#define C_NIO_BORINGSSL_H

HEADER
        for header in $(ls CNIOBoringSSL_*.h | sort); do
            case "$header" in
                CNIOBoringSSL_prefix_symbols.h|CNIOBoringSSL_prefix_symbols_internal_c.h|CNIOBoringSSL_prefix_symbols_internal_S.h) continue;;
            esac
            echo "#include \"$header\""
        done
        echo ""
        echo "#endif  // C_NIO_BORINGSSL_H"
    } > CNIOBoringSSL.h
)
cat << EOF > "$DSTROOT/include/module.modulemap"
module CNIOBoringSSL {
    umbrella header "CNIOBoringSSL.h"
    export *
}
EOF

echo "RECORDING BoringSSL revision"
$sed -i -e "s/BoringSSL Commit: [0-9a-f]\+/BoringSSL Commit: ${BORINGSSL_REVISION}/" "$HERE/Package"*.swift
echo "This directory is derived from BoringSSL cloned from https://boringssl.googlesource.com/boringssl at revision ${BORINGSSL_REVISION}" > "$DSTROOT/hash.txt"

echo "CLEANING temporary directory"
rm -rf "${TMPDIR}"
